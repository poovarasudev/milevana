// invites/{code} — the owner mints and cancels single-use invites; a linked
// user joins by marking the invite in the same batch that adds their member
// record (SHR-04/06, SD-01/03/05). Code generation and the validity helper
// live in src/domain/invites.ts.

import { arrayUnion, RepoError } from '../adapter';
import { INVITE_TTL_MS, normalizeCode } from '../../domain/invites';
import { SCHEMA_VERSION } from '../schema/common';
import { InviteDoc, inviteDocSchema } from '../schema/invite';
import { RepoBase } from './base';
import type { VehicleRecord } from './vehicleRepo';

export interface InviteRecord extends InviteDoc {
  /** The 8-character code — the document id. */
  code: string;
}

export class InviteRepo extends RepoBase {

  /**
   * Read an invite by its exact code. Any signed-in user may read an existing
   * invite (SD-01); a missing doc reads as absent. The rules deny the read
   * when the vehicle no longer exists, so a permission-denied here means
   * "This vehicle no longer exists" — callers must not swallow it (this is
   * why `get` does not use safeGet).
   */
  async get(code: string): Promise<InviteRecord | null> {
    const normalized = normalizeCode(code);
    const path = `invites/${normalized}`;
    const snap = await this.adapter.getDoc(path);
    if (!snap.exists) return null;
    const doc = this.parse('invites', inviteDocSchema, snap, path);
    return doc && { ...doc, code: normalized };
  }

  /**
   * All of the caller's invites for a vehicle (owner query, SD-05). The
   * vehicleId filter runs client-side so no composite index is required.
   */
  async listForVehicle(vehicleId: string): Promise<InviteRecord[]> {
    const uid = this.callerUid();
    const snap = await this.adapter.getDocs({
      collection: 'invites',
      clauses: [{ kind: 'where', field: 'ownerId', op: '==', value: uid }],
    });
    const out: InviteRecord[] = [];
    for (const d of snap.docs) {
      const doc = this.parse('invites', inviteDocSchema, d, `invites/${d.id}`);
      if (doc && doc.vehicleId === vehicleId) out.push({ ...doc, code: d.id });
    }
    return out;
  }

  /**
   * Mint an invite for the vehicle the caller owns. `code` is generated by
   * the caller (secure random → domain/invites); a set() on a taken code is a
   * rules 'update' and is denied, surfacing as permission-denied so the caller
   * can regenerate and retry (SD-02).
   */
  async create(vehicle: VehicleRecord, code: string): Promise<InviteRecord> {
    const uid = this.callerUid();
    if (vehicle.ownerId !== uid) {
      throw new RepoError('permission-denied', 'only the owner can invite');
    }
    const createdAt = this.adapter.now();
    const doc: InviteDoc = {
      vehicleId: vehicle.id,
      vehicleName: vehicle.name,
      ownerId: uid,
      // The joiner reads this before they can read the vehicle — fall back
      // to the auth profile when the member record has no name yet.
      ownerName: vehicle.members[uid]?.name ?? this.adapter.currentUser()?.displayName ?? '',
      createdBy: uid,
      createdAt,
      expiresAt: { seconds: createdAt.seconds + INVITE_TTL_MS / 1000, nanoseconds: createdAt.nanoseconds },
      schemaVersion: SCHEMA_VERSION,
    };
    await this.finishWrite(this.adapter.setDoc(`invites/${code}`, inviteDocSchema.parse(doc)));
    return { ...doc, code };
  }

  /** The owner cancels a pending invite by deleting the document. */
  async cancel(code: string): Promise<void> {
    await this.finishWrite(this.adapter.deleteDoc(`invites/${normalizeCode(code)}`));
  }

  /**
   * Mirror the vehicle's archived flag onto this invite (SHR-08): the joiner
   * cannot read the vehicle, so the flag is what lets them see "vehicle
   * archived" distinctly from "full". Rules allow the owner to change only
   * this field.
   */
  async setArchivedFlag(code: string, archived: boolean): Promise<void> {
    await this.finishWrite(
      this.adapter.updateDoc(`invites/${normalizeCode(code)}`, { vehicleArchived: archived }),
    );
  }

  /**
   * Join the vehicle this invite points to. One batch: the joiner's member
   * record + memberIds entry on the vehicle, and usedBy/usedAt on the invite
   * (SD-03). The joiner cannot read the vehicle, so memberIds uses an
   * arrayUnion and the member record a dot-path. `ack` is awaited on every
   * platform — the join is only real once the server confirms it, and a
   * doomed write must not sit in the offline queue as a later sync issue.
   */
  async join(invite: InviteRecord, profile: { name: string; email: string }): Promise<string> {
    const uid = this.callerUid();
    const now = this.adapter.now();
    const b = this.adapter.batch();
    b.update(`vehicles/${invite.vehicleId}`, {
      memberIds: arrayUnion([uid]),
      [`members.${uid}`]: {
        role: 'member',
        name: profile.name,
        email: profile.email,
        joinedAt: now,
        inviteCode: invite.code,
      },
      updatedAt: now,
    });
    b.update(`invites/${invite.code}`, { usedBy: uid, usedAt: now });
    const h = this.adapter.commit(b);
    await h.ack;
    return invite.vehicleId;
  }
}
